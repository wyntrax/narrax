import {render,screen,act,cleanup} from '@testing-library/react';
import {afterEach,it,expect,vi} from 'vitest';
import {NextIntlClientProvider} from 'next-intl';
import type {ReactNode} from 'react';
import messages from '../../../messages/en.json';
import {MarketingNavigation} from './navigation';
vi.mock('@/i18n/navigation',()=>({usePathname:()=> '/',Link:({href,children,onClick,'aria-current':current}:{href:string;children:ReactNode;onClick?:()=>void;'aria-current'?:'location'})=><a href={href} onClick={onClick} aria-current={current}>{children}</a>}));
afterEach(()=>{cleanup();vi.restoreAllMocks();vi.unstubAllGlobals();});
it('highlights the section under the sticky header without moving keyboard focus',()=>{
 const positions:Record<string,number>={home:0,how:800,preview:1600,access:2400,faq:3200};
 vi.spyOn(HTMLElement.prototype,'getBoundingClientRect').mockImplementation(function(this:HTMLElement){return {top:positions[this.id]??0,height:80} as DOMRect;});
 let frame:FrameRequestCallback|undefined;
 vi.stubGlobal('requestAnimationFrame',(callback:FrameRequestCallback)=>{frame=callback;return 1;});
 vi.stubGlobal('cancelAnimationFrame',vi.fn());
 render(<NextIntlClientProvider locale="en" messages={messages}><header className="site-header"><MarketingNavigation/></header><main className="landing-page">{Object.keys(positions).map(id=><section id={id} key={id}/>)}</main></NextIntlClientProvider>);
 expect(screen.getByRole('link',{name:'Home'})).toHaveAttribute('aria-current','location');
 screen.getByRole('link',{name:'Product'}).focus();
 positions.how=100;
 act(()=>{window.dispatchEvent(new Event('scroll'));frame?.(0);});
 expect(screen.getByRole('link',{name:'How it works'})).toHaveAttribute('aria-current','location');
 expect(screen.getByRole('link',{name:'Home'})).not.toHaveAttribute('aria-current');
 expect(document.activeElement).toBe(screen.getByRole('link',{name:'Product'}));
 positions.faq=80;
 act(()=>{window.dispatchEvent(new Event('scroll'));frame?.(0);});
 expect(screen.getByRole('link',{name:'FAQ'})).toHaveAttribute('aria-current','location');
 positions.how=800;positions.faq=3200;
 act(()=>{window.dispatchEvent(new Event('scroll'));frame?.(0);});
 expect(screen.getByRole('link',{name:'Home'})).toHaveAttribute('aria-current','location');
});
